// Writes src/modules/<id>/migrations.generated.ts from each module's
// migrations/*.sql, so `migrate()` works without reading files at runtime
// (bundlers, edge, serverless). A module without a migrations folder gets none.
import { existsSync } from 'node:fs';
import { readdir, readFile, writeFile } from 'node:fs/promises';

const modules = new URL('../src/modules/', import.meta.url);
let total = 0;
for (const entry of await readdir(modules, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const folder = new URL(`${entry.name}/`, modules);
  const dir = new URL('migrations/', folder);
  const names = existsSync(dir) ? (await readdir(dir)).filter((name) => name.endsWith('.sql')).sort() : [];
  const entries = await Promise.all(names.map(async (name) => ({ name, sql: await readFile(new URL(name, dir), 'utf8') })));
  total += entries.length;
  const body = `// Generated by scripts/embed-migrations.mjs from migrations/*.sql. Don't edit by hand.\nimport type { Migration } from '../../migrate.js';\n\nexport const MIGRATIONS: readonly Migration[] = ${JSON.stringify(entries, null, 2)};\n`;
  await writeFile(new URL('migrations.generated.ts', folder), body);
}
console.log(`Embedded ${total} site-data migrations`);
