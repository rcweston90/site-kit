// Writes src/postgres/migrations.generated.ts from migrations/*.sql, so
// `migrate()` works without reading files at runtime (bundlers, edge, serverless).
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const dir = new URL('migrations/', root);
const names = (await readdir(dir)).filter((name) => name.endsWith('.sql')).sort();
const entries = await Promise.all(names.map(async (name) => ({ name, sql: await readFile(new URL(name, dir), 'utf8') })));
const body = `// Generated by scripts/embed-migrations.mjs from migrations/*.sql. Don't edit by hand.\nimport type { Migration } from './migrate.js';\n\nexport const BUNDLED_MIGRATIONS: readonly Migration[] = ${JSON.stringify(entries, null, 2)};\n`;
const out = new URL('src/postgres/migrations.generated.ts', root);
await writeFile(out, body);
console.log(`Embedded ${entries.length} migrations in ${fileURLToPath(out).split('/').slice(-3).join('/')}`);
