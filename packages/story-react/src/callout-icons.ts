const icons = new Map<string, IconItem>(CALLOUT_ICON_GROUPS.flatMap(group => (group.icons as readonly IconItem[]).map(item => [item[0], item] as const)));
export function calloutIconOption(icon?: string): IconItem | undefined { return icon ? icons.get(icon) : undefined; }
export function resolvedCalloutIcon(legacy?: string, override?: string): string | undefined {
  return calloutIconOption(override)?.[0] ?? calloutIconOption(legacy)?.[0];
}
